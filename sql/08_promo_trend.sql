-- ============================================================
-- 08 大促前后日趋势
-- 大促转化率很高，但常见现象是"需求透支"——把前后几天的需求提前吸走
-- 取大促前后各 5 天做对照，正好覆盖典型的"预热—爆发—回弹"周期
-- ============================================================

SELECT
    DATE(ts)              AS `日期`,
    SUM(behavior = 'pv')  AS `浏览`,
    SUM(behavior = 'buy') AS `购买`,
    ROUND(SUM(behavior = 'buy') / SUM(behavior = 'pv') * 100, 3) AS `购买浏览比_pct`
FROM ecommerce.events
WHERE DATE(ts) BETWEEN '2014-12-06' AND '2014-12-16'
GROUP BY DATE(ts)
ORDER BY `日期`;

-- 结果：
--   大促前 5 天（12-06~10）日均：浏览 375948 / 购买 3322 / 转化率 0.884%
--   12-11：浏览 460329（+22.4%）/ 购买 3226（-2.9%）/ 转化率 0.701%（全期最低）
--   12-12：浏览 641507（+71%）  / 购买 15251（+359%）/ 转化率 2.377%
--   大促后 4 天（12-13~16）日均：浏览 379019 / 购买 3624 / 转化率 0.956%
--
-- 三个结论：
--   ① 12-11 是蓄水日：流量涨两成，购买反而微降，用户在等大促开始
--   ② 12-12 的爆发几乎全是净增：前一天"损失"的购买不足 3%，解释不了 4.6 倍的增量
--   ③ 大促后没有转化洼地：0.956% 甚至略高于大促前的 0.884%，未见透支
--
-- ⚠️ 局限：只能观测到大促后 4 天（12-17 已接近数据末尾），
--    需求透支通常需要 1-2 周才能显现，更长周期无法验证。

