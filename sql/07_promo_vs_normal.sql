-- ============================================================
-- 07 大促 vs 平日
-- 体检时发现 12-11、12-12 流量暴涨，看大促带来的流量质量如何
-- ============================================================

SELECT
    CASE
        WHEN DATE(ts) IN ('2014-12-11', '2014-12-12') THEN '大促期'
        ELSE '平日'
    END AS `时段`,
    COUNT(*)                 AS `事件数`,
    COUNT(DISTINCT user_id)  AS `活跃用户`,
    SUM(behavior = 'pv')     AS `浏览`,
    SUM(behavior = 'buy')    AS `购买`,
    ROUND(SUM(behavior = 'buy') / SUM(behavior = 'pv') * 100, 3) AS `购买浏览比_pct`
FROM ecommerce.events
GROUP BY `时段`;

-- 结果：大促期 1.677% vs 平日 0.974%，大促是平日的 1.72 倍
--       大促 2 天触达 8480 个用户，占全部用户的 84.8%
--
-- 结论：大促带来的不是"凑热闹的低质量流量"，而是转化率更高的流量。
-- ⚠️ 局限：高转化是折扣带来的，还是"双十二本来就有购买计划"，
--    数据分不开这两者，只能陈述相关关系。

